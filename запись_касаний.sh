#!/data/data/com.termux/files/usr/bin/sh
# Запись касаний экрана: время и координаты.
#
# Запускать в Termux через Shizuku:
#     rish -c "sh запись_касаний.sh"
#
# Останавливать — Ctrl+C. Запись ляжет в файл касания_ГГГГММДД_ЧЧММСС.log
# рядом со скриптом.
#
# Зачем это нужно: Android не даёт приложению подсматривать касания в
# чужой игре, а угадывать их по картинке не вышло — пять подходов, и
# самый удачный читал джойстик лишь на тёмном фоне. Shizuku даёт права
# системной оболочки, и касания берутся напрямую, точными числами.

set -e

# --- 1. Находим экран среди устройств ввода --------------------------
# Экран узнаётся по тому, что он сообщает положение пальца (ABS_MT_POSITION_X,
# это код 0035). Клавиши громкости и датчики такого не умеют.
DEV=""
for d in /dev/input/event*; do
    if getevent -p "$d" 2>/dev/null | grep -q "0035"; then
        DEV="$d"
        break
    fi
done

if [ -z "$DEV" ]; then
    echo "Экран не найден среди устройств ввода."
    echo "Покажи вывод этой команды, разберёмся:"
    echo "    rish -c 'getevent -p' | grep -i -e name -e 0035"
    exit 1
fi

NAME=$(getevent -p "$DEV" 2>/dev/null | grep -i "name:" | head -1 | cut -d'"' -f2)
echo "Экран:   $DEV  ($NAME)"

# --- 2. Сколько всего точек по ширине и высоте ------------------------
# Нужно, чтобы перевести сырые числа в доли экрана: у разных телефонов
# разрешение датчика не совпадает с разрешением картинки.
getevent -p "$DEV" 2>/dev/null | grep -A1 -e "0035" -e "0036" | sed 's/^/    /'

OUT="касания_$(date +%Y%m%d_%H%M%S).log"

echo
echo "Пишу в $OUT"
echo
echo "ПОРЯДОК ДЕЙСТВИЙ:"
echo "  1. Не закрывая Termux, включи запись экрана."
echo "  2. Открой игру."
echo "  3. СРАЗУ нажми паузу и сними её — это метка для совмещения"
echo "     записи с этим журналом."
echo "  4. Играй."
echo "  5. Вернись сюда и нажми Ctrl+C."
echo
echo "Начало записи: $(date '+%Y-%m-%d %H:%M:%S.%N')"
echo "--- пошло, останавливать Ctrl+C ---"

# --- 3. Собственно запись --------------------------------------------
# -l  понятные имена событий вместо чисел
# -t  время каждого события
{
    echo "# устройство: $DEV ($NAME)"
    echo "# начало: $(date '+%Y-%m-%d %H:%M:%S.%N')"
    echo "# часы с загрузки: $(cat /proc/uptime | cut -d' ' -f1)"
    getevent -lt "$DEV"
} > "$OUT"
